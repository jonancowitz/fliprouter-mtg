function ckCreditFromCash(cashUsd: string | null | undefined): string | null {
  if (!cashUsd) return null;
  const [whole = "0", frac = "00"] = cashUsd.split(".");
  const cents = BigInt(whole) * 100n + BigInt(`${frac}00`.slice(0, 2));
  const creditCents = (cents * 130n * 2n + 100n) / 200n;
  const dollars = creditCents / 100n;
  const rem = (creditCents % 100n).toString().padStart(2, "0");
  return `${dollars.toString()}.${rem}`;
}

function makeUuid(prefixHex4: string, index: number): string {
  const hexIdx = index.toString(16).padStart(12, "0");
  return `${prefixHex4}0000-4000-8000-a000-${hexIdx}`;
}

